import { onActivated, onMounted } from 'vue'

// Обновление данных при каждом входе на экран.
//
// Сейчас в App.vue нет <keep-alive>, поэтому компонент пересоздаётся на каждом
// переходе и работает onMounted. onActivated добавлен на будущее: если экраны
// начнут кэшироваться, обновление продолжит работать без правок во вьюхах.
// Дедупликация запросов живёт в сторах — повторный вызов подхватывает уже
// летящий промис, а не шлёт второй запрос.
export function useScreenRefresh(fn) {
  onMounted(fn)
  onActivated(fn)
}
